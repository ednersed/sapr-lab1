// Блок распределителя сигналов (вариант 8).
// Последовательность y: 3,2,1,2,1,2,1,3,...
// Y - позиционный код: y=1 -> Y[0], y=2 -> Y[1], y=3 -> Y[2].
module rspsignals
(
	Q, Y
);

input [2:0] Q;
output [2:0] Y;

reg [2:0] Y;

always @(Q)
	case (Q)
		3'b000 : Y = 3'b100; // y=3
		3'b001 : Y = 3'b010; // y=2
		3'b010 : Y = 3'b001; // y=1
		3'b011 : Y = 3'b010; // y=2
		3'b100 : Y = 3'b001; // y=1
		3'b101 : Y = 3'b010; // y=2
		3'b110 : Y = 3'b001; // y=1
		3'b111 : Y = 3'b100; // y=3
		default: Y = 3'b000;
	endcase

endmodule
