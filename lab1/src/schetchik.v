// Блок счетчика прямого хода (вариант 8).
// Входная последовательность счетчика задается тумблерами D[2..0]
// (D - функции возбуждения, т.е. следующее состояние Q(t+1)),
// на выходе - текущее состояние счетчика Q(t).
// C и R оставлены как в примере методички (п.3.2).
module schetchik
(
	C, R, D, Q
);

input C;
input R;
input [2:0] D;
output [2:0] Q;

reg [2:0] Q;

always @(D)
	case (D)
		3'b001 : Q = 3'b000;
		3'b010 : Q = 3'b001;
		3'b011 : Q = 3'b010;
		3'b100 : Q = 3'b011;
		3'b101 : Q = 3'b100;
		3'b110 : Q = 3'b101;
		3'b111 : Q = 3'b110;
		3'b000 : Q = 3'b111;
		default: Q = 3'b000;
	endcase

endmodule
